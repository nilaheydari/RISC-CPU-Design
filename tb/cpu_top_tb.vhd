library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use IEEE.NUMERIC_STD.ALL;

entity cpu_top_tb is
end cpu_top_tb;

architecture Behavioral of cpu_top_tb is

-- ????? ?????? ??? ????? ?? tb ? ????? ?????
signal clk_tb : std_logic := '0';
signal rst_tb : std_logic := '1';

-- ????? ?????? ???? ????? ??
signal alu_out_tb  : std_logic_vector(15 downto 0);
signal mem_out_tb  : std_logic_vector(15 downto 0);
signal step_out_tb : std_logic_vector(3 downto 0);

-- ????? ????? ????
constant clk_period : time := 10 ns;

begin

-- ????? ??? ??? ?? ??? ?????
UUT: entity work.cpu_top
port map(
    clk => clk_tb,
    rst => rst_tb,
    alu_out => alu_out_tb,
    mem_out => mem_out_tb,
    step_out => step_out_tb
);

------------------------------------------------
-- Clock Process  (????? ????? ????)
------------------------------------------------
clk_process : process
begin
    clk_tb <= '0';
    wait for clk_period/2;

    clk_tb <= '1';
    wait for clk_period/2;
end process;

------------------------------------------------
-- Initialization Process (????? ???????? ?????)
------------------------------------------------
init_process : process
begin

    -- ???? ?????
    rst_tb <= '1';
    wait for 20 ns;

    -- ???? ?? ????
    rst_tb <= '0';

    -- ???? ???? ????? ???? ????? CPU
    wait for 200 ns;

    wait;
end process;

end Behavioral;